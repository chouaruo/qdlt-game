// 生成单个节拍（3个状态变体）
// ═══════════════════════════════════════════════════════
async function generateBeat(charId, charInfo, turn, beatDesc) {
  const market = turnToMarket(turn);
  const prompt = `你是币圈文字冒险游戏的剧情编剧。为以下角色的第${turn}回合生成3个状态变体。

角色：${charInfo.desc}
风格：${charInfo.style}
回合：第${turn}回合/30
市场周期：${MARKET_LABELS[market]}
本回合事件：${beatDesc}

为这个事件生成3个变体（同一事件，不同玩家状态下的叙述）：
1. thriving: 玩家处于上升期（资产高于预期，心态健康）→ 自信语气，大胆选项，效果偏积极
2. stable: 玩家处于平稳期 → 中性叙述，平衡选择
3. struggling: 玩家处于困境（资产低或心态差）→ 紧迫语气，逆境视角，更多挣扎

要求：
- story: 100-150字简体中文，犀利幽默，币圈黑话和真实梗
- 三个变体讲同一事件但角度/语气/后果不同
- choices: 每变体3个选项，每个≤12字中文
- effects: money为百分比(-50到100)，mind/know/luck为绝对值(±15)
- item/lose_item: 只能是 ${VALID_COINS.slice(0,10).join('/')} 等合法币种或null
- 可用占位符：{TOTAL}(总资产) {CHANGE}(变化额)
- 全中文（BTC/ETH/DeFi等专有名词除外）
- 禁止写具体金额数字

返回严格JSON数组（3个元素）：
[{"condition":"thriving","story":"...","choices":["...","...","..."],"effects":[{"money":0,"mind":0,"know":0,"luck":0,"item":null,"lose_item":null,"breakthrough":false},{...},{...}]},{"condition":"stable",...},{"condition":"struggling",...}]`;

  const text = await callAPI(prompt);
  const match = text.match(/\[[\s\S]*\]/);
  if (!match) throw new Error('No JSON array');

  return JSON.parse(match[0]).map(v => ({
    condition: v.condition || 'default',
    story: String(v.story || '').trim(),
    choices: (v.choices || []).map(c => String(c).trim()).slice(0, 3),
    effects: (v.effects || []).slice(0, 3).map(normalizeFx),
  }));
}

async function callAPI(prompt) {
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': API_KEY,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({ model: MODEL, max_tokens: 4096, temperature: 0.85, messages: [{ role: 'user', content: prompt }] }),
  });
  if (!res.ok) throw new Error(`API ${res.status}: ${(await res.text()).slice(0, 300)}`);
  const data = await res.json();
  return data.content?.map(c => c.text).join('') || '';
}

function normalizeFx(fx) {
  return {
    money: Math.max(-50, Math.min(100, Number(fx?.money) || 0)),
    mind: Math.max(-15, Math.min(15, Number(fx?.mind) || 0)),
    know: Math.max(-15, Math.min(15, Number(fx?.know) || 0)),
    luck: Math.max(-10, Math.min(10, Number(fx?.luck) || 0)),
    item: (fx?.item && VALID_COINS.includes(fx.item)) ? fx.item : null,
    lose_item: (fx?.lose_item && VALID_COINS.includes(fx.lose_item)) ? fx.lose_item : null,
    breakthrough: Boolean(fx?.breakthrough),
  };
}

